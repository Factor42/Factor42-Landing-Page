#!/usr/bin/env node
/**
 * Bundle the HTML email templates into a Workers-safe JS module so the
 * /api/submit Pages Function can render them at runtime (no filesystem access
 * in the Functions runtime). Re-run whenever email-templates/*.html change.
 *
 * Usage: node scripts/build-email-templates.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(ROOT, 'email-templates', f), 'utf8');

const out =
  '// AUTO-GENERATED by scripts/build-email-templates.mjs — do not edit by hand.\n' +
  `export const contactConfirmation = ${JSON.stringify(read('email-contact-confirmation.html'))};\n` +
  `export const consultationConfirmation = ${JSON.stringify(read('email-consultation-confirmation.html'))};\n`;

writeFileSync(join(ROOT, 'functions', 'api', '_email-templates.js'), out, 'utf8');
console.log('Wrote functions/api/_email-templates.js');
