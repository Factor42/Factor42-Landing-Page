#!/usr/bin/env node
/**
 * Generate public/_redirects — 301s from the old *.html URLs to the new routes,
 * so existing links/rankings survive the migration. Cloudflare Pages reads this
 * file from the build output root.
 *
 * Usage: node scripts/gen-redirects.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Static marketing/legal pages that moved from /x.html -> /x
const pages = [
  'about', 'careers', 'consultation', 'contact', 'white-label-ppc', 'library',
  'privacy-policy', 'terms-of-service', 'security', 'sla',
];

const lines = ['# Auto-generated by scripts/gen-redirects.mjs — old .html URLs -> new routes'];
lines.push('/index.html            /                     301');
lines.push('/blog.html             /blog                 301');
for (const p of pages) lines.push(`/${p}.html`.padEnd(23) + ` /${p}`.padEnd(22) + ' 301');

// Blog posts: /blog-<slug>.html -> /blog/<slug>
const slugs = readdirSync(join(ROOT, 'src', 'content', 'blog'))
  .filter((f) => f.endsWith('.md'))
  .map((f) => f.replace(/\.md$/, ''))
  .sort();
lines.push('');
lines.push('# Blog posts');
for (const s of slugs) lines.push(`/blog-${s}.html`.padEnd(48) + ` /blog/${s}`.padEnd(40) + ' 301');

writeFileSync(join(ROOT, 'public', '_redirects'), lines.join('\n') + '\n', 'utf8');
console.log(`Wrote public/_redirects (${pages.length + slugs.length + 2} redirects, ${slugs.length} blog posts)`);
